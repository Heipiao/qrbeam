export const translations: Record<SupportedLocale, Dictionary> = {
  'zh-Hans': zhHans,
  en,
  ja,
  ko,
  de,
};

export function normalizeLocale(value?: string | null): SupportedLocale {
  const normalized = (value ?? '').replace('_', '-').toLowerCase();
  if (normalized.startsWith('en')) return 'en';
  if (normalized.startsWith('ja')) return 'ja';
  if (normalized.startsWith('ko')) return 'ko';
  if (normalized.startsWith('de')) return 'de';
  if (normalized.startsWith('zh')) return 'zh-Hans';
  return 'zh-Hans';
}

function detectedLocale(): string | undefined {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale;
  } catch {
    return undefined;
  }
}

const systemLocale = normalizeLocale(detectedLocale());
export let locale: SupportedLocale = systemLocale;

export function normalizeLanguagePreference(value: unknown): LanguagePreference {
  return value === 'system' ||
    value === 'zh-Hans' ||
    value === 'en' ||
    value === 'ja' ||
    value === 'ko' ||
    value === 'de'
    ? value
    : 'system';
}

export function applyLanguagePreference(
  preference: LanguagePreference,
): SupportedLocale {
  locale = preference === 'system' ? systemLocale : preference;
  return locale;
}

export function t(
  key: TranslationKey,
  parameters: Record<string, string | number> = {},
): string {
  let value: string = translations[locale][key];
  for (const [name, replacement] of Object.entries(parameters)) {
    value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement));
  }
  return value;
}

const localeTags: Record<SupportedLocale, string> = {
  'zh-Hans': 'zh-CN',
  en: 'en-US',
  ja: 'ja-JP',
  ko: 'ko-KR',
  de: 'de-DE',
};

export function formatLocalizedDate(value?: string): string | undefined {
  if (value == null) return undefined;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return undefined;
  return new Intl.DateTimeFormat(localeTags[locale], {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  }).format(date);
}

export function userFacingError(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  if (message.includes('Files must be 5 MiB or smaller')) return t('error.fileMax5');
  if (message.includes('could not be read completely')) return t('error.fileIncomplete');
  if (message.includes('subscriptions are available only in the iOS app')) {
    return t('error.subscriptionIosOnly');
  }
  return message;
}
